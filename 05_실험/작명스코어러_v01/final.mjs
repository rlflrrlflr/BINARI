    const yy=[s,a,b].map(v=>v%2?"양":"음"); const S4=yy.every(v=>v===yy[0])?0:10;
    const EL5=["수","목","목","화","화","토","토","금","금","수"];
    const tri=[s,s+a,a+b].map(v=>EL5[v%10]); const T=chain(tri); const S5=10*T.ok/T.t;
    const tot=Math.round(S1+S2+S3+S4+S5);
