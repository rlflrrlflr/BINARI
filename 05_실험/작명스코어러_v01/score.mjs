// 발음오행 두 체계 (초성)
const HAE = { ㄱ:"목",ㅋ:"목", ㄴ:"화",ㄷ:"화",ㄹ:"화",ㅌ:"화", ㅁ:"토",ㅂ:"토",ㅍ:"토", ㅅ:"금",ㅈ:"금",ㅊ:"금", ㅇ:"수",ㅎ:"수" }; // 훈민정음 해례본(학계)
const UNH = { ㄱ:"목",ㅋ:"목", ㄴ:"화",ㄷ:"화",ㄹ:"화",ㅌ:"화", ㅁ:"수",ㅂ:"수",ㅍ:"수", ㅅ:"금",ㅈ:"금",ㅊ:"금", ㅇ:"토",ㅎ:"토" }; // 운해·사성통해(업계 99%)

const CHO = ["ㄱ","ㄲ","ㄴ","ㄷ","ㄸ","ㄹ","ㅁ","ㅂ","ㅃ","ㅅ","ㅆ","ㅇ","ㅈ","ㅉ","ㅊ","ㅋ","ㅌ","ㅍ","ㅎ"];
const DBL = { ㄲ:"ㄱ", ㄸ:"ㄷ", ㅃ:"ㅂ", ㅆ:"ㅅ", ㅉ:"ㅈ" };
function cho(k){ const c = CHO[Math.floor((k.charCodeAt(0)-0xAC00)/588)]; return DBL[c]||c; }

function chain(els, map){         // 인접쌍 상생/비화 개수
  let ok=0, tot=0;
  for(let i=0;i<els.length-1;i++){
    tot++;
    const a=els[i], b=els[i+1];
    if(SANG[a]===b || a===b) ok++;          // 상생 또는 비화
  }
  return {ok,tot};
}

function score(c){
  const [n1,n2] = c.hanja;                                  // {ch, read, st, el}
  const s = SUR.st, a = n1.st, b = n2.st;

  // ① 자원오행 = 용신(金·水) 보완
  const need = new Set(["금","수"]);
  const fill = [n1.el, n2.el].filter(e=>need.has(e)).length; // 0~2
  const S1 = fill===2 ? 35 : fill===1 ? 20 : 0;

  // ② 발음오행 (해례본 12.5 + 운해 12.5)
  const reads = [SUR.read, n1.read, n2.read];
  const ph = (M)=>{ const e=reads.map(r=>M[cho(r)]); const {ok,tot}=chain(e,M); return {pts: 12.5*ok/tot, els:e.join("-"), ok, tot}; };
  const H = ph(HAE), U = ph(UNH);
  const S2 = H.pts + U.pts;

  // ③ 81수리 사격
  const four = { 원:a+b, 형:s+a, 이:s+b, 정:s+a+b };
  const gil = Object.values(four).filter(v=>GIL.has(v%81===0?81:(v>81?v-80:v))).length;
  const S3 = 20*gil/4;

  // ④ 수리음양
  const yy = [s,a,b].map(v=>v%2?"양":"음");
  const pure = yy.every(v=>v===yy[0]);
  const S4 = pure ? 0 : 10;

  // ⑤ 삼원오행 (천=성, 인=성+이름1, 지=이름1+이름2) 끝자리→오행
  const EL5 = ["수","목","목","화","화","토","토","금","금","수"];
  const tri = [s, s+a, a+b].map(v=>EL5[v%10]);
  const T = chain(tri, HAE);
  const S5 = 10*T.ok/T.tot;

  const total = Math.round(S1+S2+S3+S4+S5);
  return { total, S1, S2:+S2.toFixed(1), S3, S4, S5, four, gil, H, U, yy:yy.join(""), tri:tri.join("-"), fill };
}

