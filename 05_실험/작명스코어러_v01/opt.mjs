function best(name){
  const [r1,r2] = [name[0], name[1]];
  const L1 = D[r1]||[], L2 = D[r2]||[];
  let bst=null;
  for(const [c1,a,e1] of L1) for(const [c2,b,e2] of L2){
    const s=SUR.st;
    const S1 = 35*[e1,e2].filter(e=>e==="금"||e==="수").length/2;
    const reads=[SUR.read,r1,r2];
    const ph=M=>{const e=reads.map(x=>M[cho(x)]);const {ok,t}=chain(e);return{p:12.5*ok/t,s:e.join("-"),ok};};
    const Hh=ph(HAE), Uu=ph(UNH);
    const S2=Hh.p+Uu.p;
    const four={원:a+b,형:s+a,이:s+b,정:s+a+b};
    const norm=v=>v>81?v-80:(v===0?81:v);
    const gil=Object.values(four).filter(v=>GIL.has(norm(v))).length;
    const S3=20*gil/4;
    const yy=[s,a,b].map(v=>v%2?"양":"음");
    const S4=yy.every(v=>v===yy[0])?0:10;
    const EL5=["수","목","목","화","화","토","토","금","금","수"];
    const tri=[s,s+a,a+b].map(v=>EL5[v%10]);
    const T=chain(tri); const S5=10*T.ok/T.t;
    const tot=S1+S2+S3+S4+S5;
    const rec={tot:Math.round(tot),name:"강"+name,hj:c1+c2,S1,S2:+S2.toFixed(1),S3,S4,S5,four,gil,Hs:Hh.s,Us:Uu.s,Hok:Hh.ok,Uok:Uu.ok,yy:yy.join(""),tri:tri.join("-"),st:[s,a,b]};
    if(!bst||rec.tot>bst.tot) bst=rec;
  }
  return bst;
}
